<?php
/**
 * Convierte la base local MySQL (vinedo_control) a PostgreSQL / Supabase.
 * Genera: migrations/001_esquema.sql y migrations/006_datos_ejemplo.sql
 * Uso: C:\xampp\php\php.exe supabase\tools\mysql_a_postgres.php
 */
$pdo = new PDO('mysql:host=127.0.0.1;dbname=vinedo_control;charset=utf8mb4', 'root', '', [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC]);
$out = dirname(__DIR__) . '/migrations';
@mkdir($out, 0775, true);

// Tablas del sistema PHP que en Supabase se reemplazan (auth.users + perfiles)
$skip = ['usuarios', 'sesiones'];
$uuidCols = ['created_by', 'usuario_id'];   // pasan a uuid (auth.users)
$noData = ['bitacora', 'respaldos', 'archivos'];

$tables = array_column($pdo->query("SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA='vinedo_control' AND TABLE_TYPE='BASE TABLE'")->fetchAll(), 'TABLE_NAME');
$tables = array_values(array_diff($tables, $skip));

// Orden por dependencias (FK)
$deps = [];
foreach ($pdo->query("SELECT TABLE_NAME t, REFERENCED_TABLE_NAME r FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA='vinedo_control' AND REFERENCED_TABLE_NAME IS NOT NULL") as $r) {
    if ($r['t'] !== $r['r']) $deps[$r['t']][] = $r['r'];
}
$ordered = [];
$visit = function ($t) use (&$visit, &$ordered, $deps, $tables) {
    if (in_array($t, $ordered, true) || !in_array($t, $tables, true)) return;
    foreach ($deps[$t] ?? [] as $d) if ($d !== $t) $visit($d);
    $ordered[] = $t;
};
foreach ($tables as $t) $visit($t);

$enums = '';
$ddl = '';
$fkSql = '';
$colTypes = [];
foreach ($ordered as $t) {
    $cols = $pdo->query("SELECT * FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='vinedo_control' AND TABLE_NAME='$t' ORDER BY ORDINAL_POSITION")->fetchAll();
    $lines = [];
    foreach ($cols as $c) {
        $n = $c['COLUMN_NAME'];
        $dt = $c['DATA_TYPE'];
        $ct = $c['COLUMN_TYPE'];
        $def = $c['COLUMN_DEFAULT'];
        if ($def === 'NULL') $def = null;
        $null = $c['IS_NULLABLE'] === 'NO' ? ' not null' : '';
        if ($c['EXTRA'] === 'auto_increment') { $lines[] = "  $n integer generated by default as identity primary key"; $colTypes[$t][$n] = 'int'; continue; }
        if (in_array($n, $uuidCols, true)) { $type = 'uuid'; $def = $n === 'created_by' ? 'auth.uid()' : null; }
        elseif ($dt === 'enum') {
            preg_match_all("/'((?:[^']|'')*)'/", $ct, $m);
            $tn = "e_{$t}_{$n}";
            $enums .= "create type $tn as enum (" . implode(', ', array_map(fn($v) => "'" . str_replace("'", "''", $v) . "'", $m[1])) . ");\n";
            $type = $tn;
            if ($def !== null) $def = "'" . trim($def, "'") . "'";
        } elseif ($dt === 'tinyint' && str_contains($ct, '(1)')) { $type = 'boolean'; if ($def !== null) $def = $def ? 'true' : 'false'; $colTypes[$t][$n] = 'bool'; }
        elseif (in_array($dt, ['int', 'smallint', 'mediumint', 'tinyint'])) $type = 'integer';
        elseif ($dt === 'bigint') $type = 'bigint';
        elseif ($dt === 'decimal') $type = "numeric({$c['NUMERIC_PRECISION']},{$c['NUMERIC_SCALE']})";
        elseif ($dt === 'varchar') $type = "varchar({$c['CHARACTER_MAXIMUM_LENGTH']})";
        elseif ($dt === 'char') $type = "char({$c['CHARACTER_MAXIMUM_LENGTH']})";
        elseif (in_array($dt, ['text', 'longtext', 'mediumtext'])) $type = in_array($n, ['geom', 'geom_plano']) ? 'jsonb' : ($n === 'datos_antes' || $n === 'datos_despues' ? 'jsonb' : 'text');
        elseif ($dt === 'datetime' || $dt === 'timestamp') { $type = 'timestamptz'; if ($def && stripos($def, 'current_timestamp') !== false) $def = 'now()'; }
        elseif ($dt === 'date') $type = 'date';
        elseif ($dt === 'time') $type = 'time';
        else $type = $dt;
        $colTypes[$t][$n] ??= $type;
        if ($def !== null && $def !== 'NULL' && !str_contains($type, 'e_') && !in_array($type, ['boolean', 'timestamptz', 'uuid'])) {
            $def = is_numeric(trim($def, "'")) ? trim($def, "'") : "'" . trim($def, "'") . "'";
        }
        $d = ($def !== null && $def !== 'NULL') ? " default $def" : '';
        $lines[] = "  $n $type$null$d";
    }
    // Únicos
    foreach ($pdo->query("SELECT INDEX_NAME i, GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) c FROM information_schema.STATISTICS WHERE TABLE_SCHEMA='vinedo_control' AND TABLE_NAME='$t' AND NON_UNIQUE=0 AND INDEX_NAME<>'PRIMARY' GROUP BY INDEX_NAME") as $u) {
        $lines[] = "  unique ({$u['c']})";
    }
    $ddl .= "create table public.$t (\n" . implode(",\n", $lines) . "\n);\n";
    if (isset($colTypes[$t]['updated_at'])) $ddl .= "create trigger trg_{$t}_updated before update on public.$t for each row execute function public.set_updated_at();\n";
    $ddl .= "\n";
    // FKs (se agregan al final para permitir autorreferencias)
    $fks = $pdo->query("SELECT k.CONSTRAINT_NAME cn, k.COLUMN_NAME c, k.REFERENCED_TABLE_NAME r, rc.DELETE_RULE d
        FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS rc ON rc.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND rc.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA
        WHERE k.TABLE_SCHEMA='vinedo_control' AND k.TABLE_NAME='$t' AND k.REFERENCED_TABLE_NAME IS NOT NULL")->fetchAll();
    foreach ($fks as $f) {
        if (in_array($f['r'], $skip, true)) continue;
        $rule = $f['d'] === 'CASCADE' ? ' on delete cascade' : ($f['d'] === 'SET NULL' ? ' on delete set null' : '');
        $fkSql .= "alter table public.$t add foreign key ({$f['c']}) references public.{$f['r']}(id)$rule;\n";
        $fkSql .= "create index on public.$t ({$f['c']});\n";
    }
}

$head = "-- =====================================================================\n-- Control de Viñedo · Esquema PostgreSQL / Supabase (generado desde MySQL)\n-- =====================================================================\n"
    . "create extension if not exists pgcrypto;\n\n"
    . "create or replace function public.set_updated_at() returns trigger language plpgsql as \$\$ begin new.updated_at := now(); return new; end \$\$;\n\n"
    . "-- Perfiles de usuario (reemplaza la tabla usuarios del PHP; la contraseña la maneja Supabase Auth)\n"
    . "create type e_perfiles_rol as enum ('admin','gerencia','administracion','agronomo','tecnico','capataz','balancero','almacenero','consulta');\n"
    . "create table public.perfiles (\n  id uuid primary key references auth.users(id) on delete cascade,\n  nombre varchar(120) not null,\n  email varchar(160) not null unique,\n  rol e_perfiles_rol not null default 'consulta',\n  activo boolean not null default true,\n  ultimo_acceso timestamptz,\n  created_at timestamptz default now(),\n  updated_at timestamptz default now()\n);\n"
    . "create trigger trg_perfiles_updated before update on public.perfiles for each row execute function public.set_updated_at();\n\n";
file_put_contents("$out/001_esquema.sql", $head . $enums . "\n" . $ddl . "-- Llaves foráneas\n" . $fkSql);

// ---------------- Datos de ejemplo ----------------
$data = "-- Datos de ejemplo (generados desde la base local)\nset session_replication_role = replica;\n";
foreach ($ordered as $t) {
    if (in_array($t, $noData, true)) continue;
    $rows = $pdo->query("SELECT * FROM `$t`")->fetchAll();
    if (!$rows) continue;
    $cols = array_keys($rows[0]);
    $vals = [];
    foreach ($rows as $r) {
        $v = [];
        foreach ($r as $k => $x) {
            if ($x === null || in_array($k, $uuidCols, true)) { $v[] = 'null'; continue; }
            $ty = $colTypes[$t][$k] ?? '';
            if ($ty === 'bool') $v[] = $x ? 'true' : 'false';
            elseif ($ty === 'jsonb') $v[] = "'" . str_replace("'", "''", $x) . "'::jsonb";
            elseif (is_numeric($x) && !preg_match('/^0\d/', $x) && in_array(true, [str_starts_with($ty, 'numeric'), $ty === 'integer', $ty === 'int', $ty === 'bigint'], true)) $v[] = $x;
            elseif ($ty === 'timestamptz') $v[] = "'" . $x . "-04'";
            else $v[] = "'" . str_replace("'", "''", $x) . "'";
        }
        $vals[] = '(' . implode(',', $v) . ')';
    }
    foreach (array_chunk($vals, 300) as $chunk) {
        $data .= "insert into public.$t (" . implode(',', $cols) . ") overriding system value values\n" . implode(",\n", $chunk) . ";\n";
    }
    $data .= "select setval(pg_get_serial_sequence('public.$t','id'), coalesce((select max(id) from public.$t), 1));\n";
}
$data .= "set session_replication_role = origin;\n";
file_put_contents("$out/006_datos_ejemplo.sql", $data);
echo "OK: " . count($ordered) . " tablas\n";
